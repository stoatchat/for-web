#!/usr/bin/env node
/**
 * One-time setup for production E2E tests against invite-only instances.
 *
 * Requires SSH access to the VPS (alias `stoat`) to insert a MongoDB invite.
 * Creates the test account, completes onboarding, and creates a dedicated server.
 *
 * Usage:
 *   node scripts/setup-e2e-account.mjs
 *
 * Writes packages/client/.env.test (gitignored).
 */

import { execSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ENV_PATH = resolve(__dirname, "../.env.test");

const API_URL =
  process.env.E2E_API_URL ?? "https://stoat.viniciusrangel.dev/api";
const EMAIL =
  process.env.E2E_EMAIL ?? `stoat-e2e+${Date.now()}@viniciusrangel.dev`;
const PASSWORD =
  process.env.E2E_PASSWORD ?? `E2eTest-${randomBytes(12).toString("hex")}!`;
const USERNAME = process.env.E2E_USERNAME ?? "e2e-test-bot";

async function api(path, { method = "GET", token, body } = {}) {
  const response = await fetch(`${API_URL}${path}`, {
    method,
    headers: {
      "Content-Type": "application/json",
      ...(token ? { "X-Session-Token": token } : {}),
    },
    ...(body ? { body: JSON.stringify(body) } : {}),
  });

  const text = await response.text();
  if (!response.ok && response.status !== 204) {
    throw new Error(`${method} ${path} → ${response.status}: ${text}`);
  }

  return text ? JSON.parse(text) : null;
}

function createInvite() {
  const invite = randomBytes(16).toString("hex");
  console.log(`Creating invite ${invite} on VPS…`);

  execSync(
    `ssh -o BatchMode=yes stoat 'cd ~/stoat && sudo docker compose exec -T database mongosh revolt --quiet --eval "db.account_invites.insertOne({ _id: \\"${invite}\\" })"'`,
    { stdio: "inherit" },
  );

  return invite;
}

async function main() {
  const invite = createInvite();

  console.log(`Registering ${EMAIL}…`);
  await api("/auth/account/create", {
    method: "POST",
    body: { email: EMAIL, password: PASSWORD, invite },
  });

  console.log("Logging in…");
  const session = await api("/auth/session/login", {
    method: "POST",
    body: {
      email: EMAIL,
      password: PASSWORD,
      friendly_name: "Stoat E2E Setup",
    },
  });

  if (session.result !== "Success") {
    throw new Error(`Login failed: ${JSON.stringify(session)}`);
  }

  console.log(`Completing onboarding as ${USERNAME}…`);
  await api("/onboard/complete", {
    method: "POST",
    token: session.token,
    body: { username: USERNAME },
  });

  console.log("Creating E2E test server…");
  const created = await api("/servers/create", {
    method: "POST",
    token: session.token,
    body: { name: "E2E Test Server" },
  });

  const serverId = created.server._id;
  const channelId = created.channels[0]._id;

  const env = `# Generated by scripts/setup-e2e-account.mjs — do not commit
E2E_BASE_URL=https://stoat.viniciusrangel.dev/app
E2E_API_URL=${API_URL}
E2E_EMAIL=${EMAIL}
E2E_PASSWORD=${PASSWORD}
E2E_SERVER_ID=${serverId}
E2E_CHANNEL_ID=${channelId}
`;

  writeFileSync(ENV_PATH, env, "utf8");

  console.log(`\nWrote ${ENV_PATH}`);
  console.log(`Server: ${serverId}`);
  console.log(`Channel: ${channelId}`);
  console.log("\nRun: pnpm test:e2e:prod");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
